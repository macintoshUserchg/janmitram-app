export const INDIAN_STATES = Object.keys(INDIA_STATES_CITIES).sort();

/**
 * Get sorted cities list for a given state name.
 */
export function getCitiesForState(stateName) {
    if (!stateName) return [];
    
    // Exact or normalized match
    const matchedState = Object.keys(INDIA_STATES_CITIES).find(
        (s) => s.toLowerCase() === stateName.trim().toLowerCase()
    );
    
    if (matchedState && INDIA_STATES_CITIES[matchedState]) {
        return [...INDIA_STATES_CITIES[matchedState]].sort();
    }
    
    return [];
}

/**
 * Match a city name back to its state (useful for reverse-geocoding).
 */
export function findStateForCity(cityName) {
    if (!cityName) return null;
    const cleanCity = cityName.trim().toLowerCase();
    
    for (const [state, cities] of Object.entries(INDIA_STATES_CITIES)) {
        if (cities.some(c => c.toLowerCase() === cleanCity || cleanCity.includes(c.toLowerCase()) || c.toLowerCase().includes(cleanCity))) {
            return state;
        }
    }
    return null;
}
